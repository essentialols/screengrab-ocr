#
# Creates a Quick Action (Service) that runs screengrab-ocr.
# After install, assign a keyboard shortcut in:
#   System Settings > Keyboard > Keyboard Shortcuts > Services
# Suggested: Cmd+Shift+2
#
set -euo pipefail

